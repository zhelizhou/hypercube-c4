"""Generate a separately audited checker with original-unit preprocessing.

Only assignments obtained by unit propagation from ORIGINAL axioms are cached.
Every input/derived clause is simplified by these already proved units.
"""
from pathlib import Path

root=Path(__file__).resolve().parent
s=(root/'check_rup_active.cpp').read_text()


def replace(old,new):
    global s
    assert s.count(old)==1,old
    s=s.replace(old,new)


replace('int nv;vector<Clause>cs;', 'int nv;vector<int>base;bool contradiction;vector<Clause>cs;')
replace('Checker(int n):nv(n),watch(2*n+2),assignment(n+1){}',
        'Checker(int n,const vector<int>&b,bool conflict):nv(n),base(b),contradiction(conflict),watch(2*n+2),assignment(n+1){}')
replace('fill(assignment.begin(),assignment.end(),0);queue.clear();used.clear();',
        'assignment=base;queue.clear();used.clear();if(contradiction)return true;')
replace('void add(vector<int>v,bool original=false){', '''bool simplify(vector<int>&v){
  vector<int>out;for(int l:v){if(abs(l)>nv||!l)exit(4);int val=base[abs(l)]*(l>0?1:-1);if(val>0)return false;if(!val)out.push_back(l);}v=move(out);return true;
 }
 void add(vector<int>v,bool original=false){
  if(!simplify(v))return;''')
replace('if(v.empty())return;', 'if(v.empty()){contradiction=true;return;}')
replace('void remove(vector<int>v){', 'void remove(vector<int>v){\n  if(!simplify(v))return;')
replace('if(nv<=0||int(input.size())!=expected)return 6;Checker checker(nv),history(nv);for(auto c:input){checker.add(c,true);history.add(c,true);}', '''if(nv<=0||int(input.size())!=expected)return 6;
 vector<int>base(nv+1);bool conflict=false,changed=true;
 // This preprocessing uses ORIGINAL AXIOMS ONLY, never proof clauses.
 while(changed&&!conflict){changed=false;for(const auto &c:input){
  bool sat=false;int open=0,last=0;for(int l:c){int val=base[abs(l)]*(l>0?1:-1);if(val>0){sat=true;break;}if(!val){open++;last=l;}}
  if(sat)continue;if(open==0){conflict=true;break;}if(open==1){base[abs(last)]=last>0?1:-1;changed=true;}
 }}
 Checker checker(nv,base,conflict),history(nv,base,conflict);for(auto c:input){checker.add(c,true);history.add(c,true);}''')
s='// GENERATED by build_cached_checker.py; original-unit simplification is documented there.\n'+s
(root/'check_rup_cached.cpp').write_text(s)
print('Generated check_rup_cached.cpp')
